import java.util.Scanner;
public class Main {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();
        // Please write your code here.
        int[][][][] dp = new int[n + 2][2][2][2];
        dp[1][0][0][0] = 1;
        
        for (int i = 1; i <= n; i++) {
            // dp[i][0][0][0]
            dp[i + 1][1][0][0] = (dp[i + 1][1][0][0] + dp[i][0][0][0]) % 10007;
            dp[i + 1][0][0][1] = (dp[i + 1][0][0][1] + dp[i][0][0][0]) % 10007;
            dp[i + 1][1][1][1] = (dp[i + 1][1][1][1] + dp[i][0][0][0]) % 10007;
            
            // dp[i][0][0][1]
            dp[i + 1][0][0][0] = (dp[i + 1][0][0][0] + dp[i][0][0][1]) % 10007;
            dp[i + 1][1][1][0] = (dp[i + 1][1][1][0] + dp[i][0][0][1]) % 10007;
            
            // dp[i][0][1][0]
            dp[i + 1][1][0][1] = (dp[i + 1][1][0][1] + dp[i][0][1][0]) % 10007;
            
            // dp[i][1][0][0]
            dp[i + 1][0][0][0] = (dp[i + 1][0][0][0] + dp[i][1][0][0]) % 10007;
            dp[i + 1][0][1][1] = (dp[i + 1][0][1][1] + dp[i][1][0][0]) % 10007;
            
            // dp[i][0][1][1]
            dp[i + 1][1][0][0] = (dp[i + 1][1][0][0] + dp[i][0][1][1]) % 10007;
            
            // dp[i][1][0][1]
            dp[i + 1][0][1][0] = (dp[i + 1][0][1][0] + dp[i][1][0][1]) % 10007;
            
            // dp[i][1][1][0]
            dp[i + 1][0][0][1] = (dp[i + 1][0][0][1] + dp[i][1][1][0]) % 10007;
            
            // dp[i][1][1][1]
            dp[i + 1][0][0][0] = (dp[i + 1][0][0][0] + dp[i][1][1][1]) % 10007;
        }
        
        System.out.println(dp[n + 1][0][0][0]);
    }
}